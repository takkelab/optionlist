import type { SqlRunner } from "./ShortLivedConnection";

export type Snapshot = {
  columns: string[];
  indexes: string[];
  foreignKeys: string[];
  checks: string[];
  // 関数（認証の関数など）。関数だけを足すマイグレーションでも、up と down の差が見えるように
  functions: string[];
  rowCounts: string[];
};

export interface SchemaReader {
  take(): Promise<Snapshot>;
}

type ColumnRow = { tableName: string; columnName: string; columnType: string; nullable: string; columnDefault: string | null; identity: string };
type IndexRow = { tableName: string; indexName: string; unique: string; columns: string };
type ForeignKeyRow = { tableName: string; definition: string; constraintName: string };
type TableRow = { tableName: string };
type FunctionRow = { name: string; args: string; result: string; owner: string; definer: string };
type CountRow = { n: number };

// dbmate の管理表。rollback しても残るので比べない
const IGNORED_TABLE = "schema_migrations";

// public スキーマのテーブル・列・索引・外部キー・CHECK と行数を pg_catalog から読み、比べやすい文字列の一覧にする（testing.md §1）
export class SchemaSnapshot implements SchemaReader {
  readonly #sql: SqlRunner;

  constructor(sql: SqlRunner) {
    this.#sql = sql;
  }

  async take(): Promise<Snapshot> {
    return {
      columns: await this.#columns(),
      indexes: await this.#indexes(),
      foreignKeys: await this.#constraints("f"),
      checks: await this.#constraints("c"),
      functions: await this.#functions(),
      rowCounts: await this.#rowCounts(),
    };
  }

  // 名前・引数・戻り値・持ち主・SECURITY DEFINER か
  async #functions(): Promise<string[]> {
    const rows = await this.#sql.rows<FunctionRow>(
      `SELECT p.proname AS name, pg_get_function_identity_arguments(p.oid) AS args, pg_get_function_result(p.oid) AS result,
              pg_get_userbyid(p.proowner) AS owner, CASE WHEN p.prosecdef THEN ' SECURITY DEFINER' ELSE '' END AS definer
         FROM pg_proc p
         JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = 'public'`,
    );
    return rows.map((r) => `${r.name}(${r.args}) RETURNS ${r.result} OWNER ${r.owner}${r.definer}`).sort();
  }

  async #columns(): Promise<string[]> {
    const rows = await this.#sql.rows<ColumnRow>(
      `SELECT c.relname AS "tableName", a.attname AS "columnName", format_type(a.atttypid, a.atttypmod) AS "columnType",
              CASE WHEN a.attnotnull THEN 'NOT NULL' ELSE 'NULL' END AS nullable,
              pg_get_expr(d.adbin, d.adrelid) AS "columnDefault",
              CASE a.attidentity WHEN 'a' THEN 'GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY' ELSE '' END AS identity
         FROM pg_attribute a
         JOIN pg_class c ON c.oid = a.attrelid
         JOIN pg_namespace n ON n.oid = c.relnamespace
         LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname <> $1 AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY c.relname, a.attnum`,
      [IGNORED_TABLE],
    );
    return rows.map((r) => {
      const fallback = r.columnDefault === null ? "" : ` DEFAULT ${r.columnDefault}`;
      return `${r.tableName}.${r.columnName} ${r.columnType} ${r.nullable}${fallback} ${r.identity}`.trim();
    });
  }

  // 定義（CREATE [UNIQUE] INDEX … USING btree (列, …) の文）から、ユニークかと列の並びを取り出す
  async #indexes(): Promise<string[]> {
    const rows = await this.#sql.rows<IndexRow>(
      `SELECT tablename AS "tableName", indexname AS "indexName",
              CASE WHEN indexdef LIKE 'CREATE UNIQUE%' THEN ' UNIQUE' ELSE '' END AS "unique",
              substring(indexdef FROM 'USING \\w+ \\((.*)\\)$') AS columns
         FROM pg_indexes WHERE schemaname = 'public' AND tablename <> $1`,
      [IGNORED_TABLE],
    );
    return rows.map((r) => `${r.tableName}.${r.indexName}${r.unique} (${r.columns})`).sort();
  }

  async #constraints(type: "f" | "c"): Promise<string[]> {
    const rows = await this.#sql.rows<ForeignKeyRow>(
      `SELECT c.relname AS "tableName", k.conname AS "constraintName", pg_get_constraintdef(k.oid) AS definition
         FROM pg_constraint k
         JOIN pg_class c ON c.oid = k.conrelid
         JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND k.contype = $1`,
      [type],
    );
    return rows.map((r) => `${r.tableName}.${r.constraintName} ${r.definition}`).sort();
  }

  async #rowCounts(): Promise<string[]> {
    const tables = await this.#sql.rows<TableRow>(
      `SELECT tablename AS "tableName" FROM pg_tables WHERE schemaname = 'public' AND tablename <> $1 ORDER BY tablename`,
      [IGNORED_TABLE],
    );
    const counts: string[] = [];
    for (const { tableName } of tables) {
      // 表の名前は pg_tables から読んだもの（入力ではない）。識別子として引用符で囲む
      const rows = await this.#sql.rows<CountRow>(`SELECT COUNT(*)::int AS n FROM "${tableName}"`);
      const [row] = rows;
      counts.push(`${tableName}: ${row?.n ?? 0}`);
    }
    return counts;
  }
}
